"""FastAPI microservice exposing the forecasting and surplus-marketing endpoints.

Run:  .venv/bin/uvicorn app.api.main:app --reload
Docs: http://127.0.0.1:8000/docs

The model is trained once at startup and held in memory. That is fine for a POC and
wrong for production, where training belongs in a scheduled job writing to a model
registry -- noted in the plan, deliberately out of scope here.
"""

from __future__ import annotations

import datetime as dt
import hmac
import os
import uuid
from contextlib import asynccontextmanager

import pandas as pd
from fastapi import FastAPI, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse

from app.api import schemas
from app.core.items import BY_SKU
from app.core.surplus import detect_surplus
from app.integration import restomind
from app.integration.registry import RestaurantRegistry
from app.marketing.copy import OfferService
from app.marketing.publisher import MetaPublisher
from app.models.service import ForecastService

STATE: dict = {}


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Prepare the service on startup so the first request is not the one that pays.

    Two start modes, chosen by the COLD_START env var:
      * default        -- load the full (simulated) history and train, as before. Every
                          item is already past the threshold, so all use the model.
      * COLD_START=true -- start with zero history. Every item is rule-based until data
                          is posted to /data/ingest. This is the cold-start demo path.
    """
    service = ForecastService(horizon=1)
    if os.getenv("COLD_START", "false").lower() == "true":
        service.start_cold()
    else:
        service.train()
    STATE["forecast"] = service
    STATE["offers"] = OfferService()
    STATE["publisher"] = MetaPublisher()
    # Per-restaurant learned levels. Persist by default. In-memory only when
    # REGISTRY_STORE is explicitly "" (which is what the test suite does to
    # stay isolated).
    store = os.getenv("REGISTRY_STORE", "data/registry.json")
    STATE["registry"] = RestaurantRegistry(persist_path=store or None)
    # Offers generated by /marketing/generate-offer, keyed by offerId, so
    # /marketing/publish can only ever post text that already passed _validate() --
    # see PublishRequest.offerId's docstring. In-memory POC store; bounded so an
    # unbounded stream of generate-offer calls can't grow this without limit.
    STATE["generated_offers"] = {}
    yield
    STATE.clear()


MAX_STORED_OFFERS = 500


app = FastAPI(
    title="Bakery Demand & Surplus AI",
    version="0.1.0",
    lifespan=lifespan,
    description=(
        "Demand forecasting and automated surplus marketing for Egyptian bakeries.\n\n"
        "**All forecasts in this POC are trained on SIMULATED data.** Figures are "
        "projections from a generated dataset with assumed unit economics, not "
        "measurements from a real bakery."
    ),
)

# Path prefixes that mutate state or trigger an outbound call (LLM, Meta Graph API)
# on someone else's behalf -- gated behind the shared secret. `/integration/restomind`
# was the original scope; `/marketing` joined it because both /generate-offer and
# /publish drive real LLM calls and, if live publishing is enabled, a real public
# Facebook/Instagram post -- an unauthenticated caller could otherwise trigger either
# for free (OWASP LLM04, Model DoS) or reach /publish directly (OWASP LLM02).
_SECRET_GATED_PREFIXES = ("/integration/restomind", "/marketing")


@app.middleware("http")
async def _require_shared_secret(request, call_next):
    """Gate the RestoMind integration + marketing routes behind a shared secret.

    These routes read and mutate per-tenant learned demand levels, or trigger paid
    LLM/social calls, so anyone who could reach the port could poison another
    restaurant's forecasts or run up its LLM/Meta bill. Disabled when
    AI_SHARED_SECRET is unset, which keeps local dev and tests unchanged.
    """
    secret = os.getenv("AI_SHARED_SECRET")
    if secret and request.url.path.startswith(_SECRET_GATED_PREFIXES):
        if not hmac.compare_digest(request.headers.get("X-RestoMind-Key", ""), secret):
            return JSONResponse(
                status_code=status.HTTP_401_UNAUTHORIZED,
                content={"error": "unauthorized",
                         "detail": "Missing or invalid X-RestoMind-Key"},
            )
    return await call_next(request)


# Allow a browser frontend to call the model directly. Defaults to the local dev
# frontend origin; set CORS_ORIGINS to a comma-separated list for other deployments.
#
# Registered AFTER the secret guard above -- Starlette builds its middleware stack so
# the LAST-registered middleware becomes OUTERMOST. CORSMiddleware must be outermost
# so it can answer OPTIONS preflights and attach Access-Control-Allow-* headers to
# every response (including a 401 from the guard); registering it first would let the
# guard's 401 short-circuit preflights before CORS ever ran, breaking every
# cross-origin browser call to a protected route regardless of whether it holds the
# correct secret.
app.add_middleware(
    CORSMiddleware,
    allow_origins=os.getenv("CORS_ORIGINS", "http://localhost:3000").split(","),
    allow_methods=["*"],
    allow_headers=["*"],
)


def _service() -> ForecastService:
    service = STATE.get("forecast")
    if service is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Forecast model is still training. Retry shortly.",
        )
    return service


@app.exception_handler(KeyError)
async def _key_error_handler(request, exc: KeyError) -> JSONResponse:
    return JSONResponse(
        status_code=status.HTTP_404_NOT_FOUND,
        content=schemas.ErrorResponse(
            error="not_found",
            detail=str(exc).strip("'\""),
            hint=f"Known SKUs: {', '.join(sorted(BY_SKU))}",
        ).model_dump(),
    )


